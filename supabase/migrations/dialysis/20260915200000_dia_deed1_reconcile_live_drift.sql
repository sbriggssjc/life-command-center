-- ---------------------------------------------------------------------------
-- 1. dia_owner_name_alias — curated, human-confirmed name-token pairings.
--    Each row asserts that alias_token and canonical_token name the SAME party
--    even though they share no substring. This is NOT an inference table — do
--    not populate it with anything the comparator could derive on its own, and
--    do not add a row without a human confirming the pairing (see `notes`).
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.dia_owner_name_alias (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias_token     text NOT NULL,
    canonical_token text NOT NULL,
    notes           text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (alias_token, canonical_token)
);

