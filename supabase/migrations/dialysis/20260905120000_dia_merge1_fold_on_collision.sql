-- MERGE1 — dia_merge_property: FOLD on collision instead of losing the child row.
--
-- Measured live 2026-09-05 (dia_property_merge_backup, 585 merges / 206 collisions):
--   property_embeddings.property_id_error           198  (UNIQUE(property_id) — re-derivable)
--   cap_rate_history.property_id_error                23  (UNIQUE(property_id,event_type,event_date) —
--                                                          substantive point-in-time value history)
--   property_metadata_backfill_queue.property_id_error 11 (UNIQUE(property_id) — queue state)
--   pending_updates.property_id_error                  1  (PARTIAL UNIQUE ... WHERE status='pending_review')
--
-- The generic properties-FK loop in dia_merge_property used to catch the unique_violation, record it
-- under "<table>.<col>_error", and leave the row pointing at drop_id — which is then silently destroyed
-- by ON DELETE CASCADE when properties.property_id = drop_id is deleted a few lines later. The backup
-- table's snapshotted child id then points at nothing, so dia_unmerge_property reports it "restored" or
-- honestly "_lost" while the data is gone either way.
--
-- Fix: every properties-FK table gets a POLICY (re_derivable / fold_fill_blanks / resolve_status).
-- On a real collision the row is never blind-deleted:
--   - re_derivable     -> the drop-side row is discarded and the discard is recorded as NOT a loss
--                         (the value is recomputed by an existing worker; keep-side row is authoritative).
--   - resolve_status   -> the drop-side row's status is flipped out of the partial-unique predicate's
--                         scope, then repointed to keep_id UNCHANGED otherwise — the row survives.
--   - fold_fill_blanks -> the drop-side row is located against its matching keep-side row (via the
--                         conflicting unique key), every column that is NULL on the keep row is filled
--                         from the drop row (COALESCE, never overwrites a keep-side value), then the
--                         drop row is deleted. The keep row now carries the union of both sides.
--   - (no policy row)  -> defaults to fold_fill_blanks off the table's own single-column PK, so an
--                         UNCLASSIFIED table is never blind-deleted either.
--
-- Discipline: additive, reversible (re-create the prior function bodies), no data mutated by this
-- migration itself — it changes behaviour for merges run AFTER this ships. The 206 historical
-- collisions are NOT touched; they are recorded in docs/audits/MERGE1_PROPERTY_MERGE_COLLISION_FOLD.md.

CREATE TABLE IF NOT EXISTS public.dia_merge_child_policy (
  table_name      text PRIMARY KEY,
  policy          text NOT NULL CHECK (policy IN ('re_derivable','fold_fill_blanks','resolve_status')),
  pk_col          text NOT NULL,
  conflict_cols   text[] NOT NULL DEFAULT '{}',
  resolve_column  text,
  resolve_value   text,
  notes           text,
  created_at      timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.dia_merge_child_policy IS
  'MERGE1: per-table fold policy consulted by dia_merge_fold_table() on a properties-FK repoint '
  'collision inside dia_merge_property(). A table with no row here defaults to fold_fill_blanks '
  'off its own single-column PK -- never a blind delete.';

